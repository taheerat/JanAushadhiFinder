    fun findResponse(query: String): String? {
        val lowerQuery = query.lowercase()
        // Check for specific questions or keywords
        for (med in medicineList) {
            if (lowerQuery.contains(med.medicineName.lowercase()) || 
                lowerQuery.contains(med.genericName.lowercase())) {
                
                // If user asks about alternative
                if (lowerQuery.contains("alternative") || lowerQuery.contains("equivalent") || lowerQuery.contains("generic")) {
                    return "The Jan Aushadhi equivalent for ${med.medicineName} is **${med.janAushadhiEquivalent}**. It contains the same active ingredient and is much more affordable."
                }
                
                // If user asks about usage
                if (lowerQuery.contains("use") || lowerQuery.contains("for") || lowerQuery.contains("what is")) {
                    return med.aiResponse
                }
                
                // Default match
                return med.aiResponse
            }
        }
        return null
    }
